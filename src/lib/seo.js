export function getRouteSeo(path) {
  return routeSeo[path];
}

function truncateDescription(value, maxLength = 160) {
  if (value.length <= maxLength) {
    return value;
  }

  const shortened = value.slice(0, maxLength + 1);
  const lastSpace = shortened.lastIndexOf(' ');
  return `${shortened.slice(0, lastSpace > 0 ? lastSpace : maxLength).trim()}.`;
}

export function getGalleryCategorySeo(category) {
  const slug = category.route.replace('category/', '');

  if (slug === 'client-3d-renderings') {
    return routeSeo['/gallery/category/client-3d-renderings'];
  }

  return {
    title: `${category.title} Sauna Gallery | Vaja`,
    description: truncateDescription(`View ${category.title} sauna gallery images from Vaja. ${category.description}`),
  };
}

export function getSeoForRoute(route) {
  if (routeSeo[route]) {
    return routeSeo[route];
  }

  const productMatch = route.match(/^\/products\/([^/]+)$/);
  if (productMatch && productSeoBySlug[productMatch[1]]) {
    return {
      ...productSeoBySlug[productMatch[1]],
      type: 'product',
    };
  }

  const blogMatch = route.match(/^\/blog\/([^/]+)$/);
  if (blogMatch) {
    return (
      blogSeoBySlug[blogMatch[1]] || {
        title: 'Blog Article | Vaja',
        description: 'Read the latest sauna and steam room insights from Vaja South Africa.',
      }
    );
  }

  const galleryMatch = route.match(/^\/gallery\/category\/([^/]+)$/);
  if (galleryMatch && galleryCategorySeoBySlug[galleryMatch[1]]) {
    return galleryCategorySeoBySlug[galleryMatch[1]];
  }

  return routeSeo['/'];
}
